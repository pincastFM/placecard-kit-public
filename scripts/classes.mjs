// Writes core/classes.js: TT_CLASSES, every class the kit names in its own namespaces (tt-, ttf-), read from its
// templates (static class, :class string literals, Transition and TransitionGroup names with Vue's suffixes), the
// components' scripts (string literals, less head keys: a literal right after `key:`), the face's root classes
// (core/face.js ttFaceClass over every side, face and face theme), and its stylesheets (css/table.css,
// css/themes/cardroom.css, css/moderation.css, the components' <style> blocks). Conformance checks an
// instance's stylesheets and markup against it (CONTRACT.md).
// Run: npm run classes. test/conformance/classes.test.js rebuilds the list and fails when the file is stale.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { parse } from 'vue/compiler-sfc'
import { ttCssRules, ttSelectorClasses } from '../conformance/css.js'
import { TT_FACES, ttFaceClass } from '../core/face.js'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const NS = /^(tt|ttf)-[\w-]+$/
// ttLook's face themes: a walk's 'pop', a destination's 'base', Treehopper's 'th', the Studio's 'pc'
const FACE_THEMES = ['pop', 'base', 'th', 'pc']
const ENTER_LEAVE = ['enter-from', 'enter-active', 'enter-to', 'leave-from', 'leave-active', 'leave-to']

export function kitClasses(root = ROOT) {
  const set = new Set()
  const add = (c) => { if (NS.test(c)) set.add(c) }
  const words = (expr) => { for (const m of String(expr).matchAll(/(['"`])((?:\\.|(?!\1)[^\\])*)\1/g)) m[2].split(/\s+/).forEach(add) }
  const sheets = [readFileSync(`${root}/css/table.css`, 'utf8'), readFileSync(`${root}/css/themes/cardroom.css`, 'utf8'), readFileSync(`${root}/css/moderation.css`, 'utf8')]
  const walk = (node) => {
    if (node.type === 1) {
      const transition = /^(Transition|TransitionGroup|transition|transition-group)$/.test(node.tag)
      for (const p of node.props) {
        if (p.type === 6 && p.name === 'class' && p.value) p.value.content.split(/\s+/).forEach(add)
        else if (p.type === 7 && p.name === 'bind' && p.arg && p.arg.content === 'class' && p.exp) words(p.exp.content)
        else if (transition && p.type === 6 && p.name === 'name' && p.value) {
          const n = p.value.content
          for (const s of ENTER_LEAVE) add(`${n}-${s}`)
          if (/group/i.test(node.tag)) add(`${n}-move`)
        }
      }
    }
    for (const c of node.children || []) walk(c)
  }
  for (const f of readdirSync(`${root}/vue`).filter(f => f.endsWith('.vue')).sort()) {
    const { descriptor } = parse(readFileSync(`${root}/vue/${f}`, 'utf8'), { filename: f })
    if (descriptor.template) walk(descriptor.template.ast)
    for (const st of descriptor.styles) sheets.push(st.content)
    for (const sc of [descriptor.script, descriptor.scriptSetup]) if (sc) words(sc.content.replace(/\bkey:\s*(['"`])(?:\\.|(?!\1)[^\\])*\1/g, ''))
  }
  for (const side of ['front', 'back']) for (const face of TT_FACES) for (const theme of FACE_THEMES) for (const photo of [true, false]) {
    for (const noimg of [false, true]) ttFaceClass({ face, theme, photo }, side, noimg).split(/\s+/).forEach(add)
  }
  for (const text of sheets) for (const r of ttCssRules(text)) for (const sel of r.selectors) ttSelectorClasses(sel).forEach(add)
  return [...set].sort()
}

export function classesModule(list) {
  const rows = []
  let row = ''
  for (const c of list) {
    const item = `'${c}',`
    if (row && row.length + item.length + 1 > 118) { rows.push(row); row = '' }
    row += (row ? ' ' : '') + item
  }
  if (row) rows.push(row)
  return `// Generated by scripts/classes.mjs (npm run classes): every class the kit names in its namespaces, tt- and ttf-,
// from its templates and stylesheets. test/conformance/classes.test.js fails when this file is stale. An instance's
// stylesheets and markup use these, its theme's class, or its own (conformance, kit CONTRACT.md sections 3 and 4).
export const TT_CLASSES = Object.freeze([
${rows.map(r => `  ${r}`).join('\n')}
])
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const list = kitClasses()
  writeFileSync(`${ROOT}/core/classes.js`, classesModule(list))
  console.log(`core/classes.js: ${list.length} classes`)
}
